def hint(text: str) -> tuple[str, str, tuple[tuple[str, str], ...]] | None:
    """Підказка, якщо текст схожий на питання про те, як користуватися ботом.

    Повертає (відповідь, розділ інструкції, кнопки) або None."""
    norm = " " + " ".join(suggest._norm(w) for w in text.split()) + " "
    for keys, guide, answer, buttons in HINTS:
        if any(" " + k in norm for k in keys):
            return answer, guide, buttons
    return None
